import { Button as ButtonPrimitive } from "@base-ui/react/button"
import { cva, type VariantProps } from "class-variance-authority"
import { cn } from "cn"

// RafaCena controls use a 44px default target and brand-colored primary and outline variants; compact variants remain for dense tools.
// Compared with upstream: reduce input fill opacity to retain text contrast; failures use a full red outline and stronger glow.
